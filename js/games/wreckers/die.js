/* หมุนช้าลงเรื่อย ๆ แล้วหยุดตรงท่านิ่งพอดี — จบที่ t = 1 ไม่มีกระตุก */
export function rollPose(t) {
  const e = 1 - Math.pow(1 - Math.min(1, Math.max(0, t)), 3);
  return {
    x: HERO.x + (1 - e) * 720,
    y: HERO.y + (1 - e) * 1080,
    z: HERO.z + (1 - e) * 540
  };
}

/* ── คณิตศาสตร์ ─────────────────────────────────────────────── */
const rad = (d) => d * Math.PI / 180;

function spin([x, y, z], p) {
  const cx = Math.cos(rad(p.x)), sx = Math.sin(rad(p.x));
  const cy = Math.cos(rad(p.y)), sy = Math.sin(rad(p.y));
  const cz = Math.cos(rad(p.z)), sz = Math.sin(rad(p.z));
  let a = x * cz - y * sz, b = x * sz + y * cz;            // รอบแกน z
  let c = a * cy + z * sy;  const d = -a * sy + z * cy;     // รอบแกน y
  const e = b * cx - d * sx, f = b * sx + d * cx;           // รอบแกน x
  return [c, e, f];
}

const sub = (a, b) => [a[0] - b[0], a[1] - b[1], a[2] - b[2]];
const cross = (a, b) => [
  a[1] * b[2] - a[2] * b[1],
  a[2] * b[0] - a[0] * b[2],
  a[0] * b[1] - a[1] * b[0]
];
const dot = (a, b) => a[0] * b[0] + a[1] * b[1] + a[2] * b[2];
function unit(a) {
  const L = Math.hypot(a[0], a[1], a[2]) || 1;
  return [a[0] / L, a[1] / L, a[2] / L];
}

/* เปอร์สเปกทีฟอ่อน ๆ — หน้าที่อยู่ใกล้กล้องใหญ่กว่านิดหน่อย
   ช่วยให้อ่านออกว่าอันไหนอยู่หน้าอยู่หลัง โดยไม่บิดจนดูเป็นภาพเลนส์กว้าง */
const DEPTH = 0.17;
const flat = (p, r) => {
  const k = r / (1 - p[2] * DEPTH);
  return [p[0] * k, -p[1] * k];                             // y ของ SVG กลับด้าน
};

/* แสงมาจากบนซ้ายเยื้องหน้า เงาจึงตกไปทางขวาล่างเหมือนของจริง */
const LIGHT = unit([-0.45, 0.78, 0.72]);
const BEVEL = 0.86;                                          // ความกว้างของขอบลบมุม

/* จุดยอดยาวเท่ากันทุกทรง แต่พอหันหน้าเข้ากล้อง ทรงที่หน้าใหญ่กว่าจะดูเล็กกว่า
   เพราะหน้าของลูกบาศก์กินพื้นที่แค่ราวครึ่งเดียวของรัศมี ตัวคูณนี้ดึงให้ทุกทรงโตเท่ากันบนจอ */
const FIT = { 4: 1.10, 6: 1.50, 12: 1.0 };
const LIT = [252, 246, 232];
const DARK = [122, 106, 80];
const mix = (t) => `rgb(${LIT.map((v, i) => Math.round(DARK[i] + (v - DARK[i]) * t)).join(',')})`;

/* ── วาด ─────────────────────────────────────────────────────
   คืนสตริง SVG ทั้งก้อน วาดใหม่ทุกเฟรมได้สบาย หน้ามากสุดแค่ 12 หน้า */
export function dieSvg(sides, pose = HERO, face = null) {
  const solid = SOLID[shapeOf(sides)];
  const R = 42 * (FIT[shapeOf(sides)] || 1);
  const pts = solid.v.map(v => spin(v, pose));

  const shown = [];
  for (const idx of solid.f) {
    const a = pts[idx[0]], b = pts[idx[1]], c = pts[idx[2]];
    let n = unit(cross(sub(b, a), sub(c, a)));
    const mid = idx.reduce((s, i) => [s[0] + pts[i][0] / idx.length,
                                      s[1] + pts[i][1] / idx.length,
                                      s[2] + pts[i][2] / idx.length], [0, 0, 0]);
    if (dot(n, mid) < 0) n = [-n[0], -n[1], -n[2]];          // เรียงจุดกลับด้านก็ยังได้ด้านนอกเสมอ
    if (n[2] <= 0.02) continue;                              // หันหลังให้กล้อง ไม่ต้องวาด

    const flatPts = idx.map(i => flat(pts[i], R));
    const mid2 = flat(mid, R);
    const inset = flatPts.map(p => [mid2[0] + (p[0] - mid2[0]) * BEVEL,
                                    mid2[1] + (p[1] - mid2[1]) * BEVEL]);
    shown.push({
      z: mid[2],
      n,
      d: flatPts.map(p => `${p[0].toFixed(2)},${p[1].toFixed(2)}`).join(' '),
      mid: mid2,
      inner: inset.map(p => `${p[0].toFixed(2)},${p[1].toFixed(2)}`).join(' '),
      span: Math.min(...flatPts.map(p => Math.hypot(p[0] - mid2[0], p[1] - mid2[1])))
    });
  }

  shown.sort((a, b) => a.z - b.z);                           // ไกลก่อน ใกล้ทีหลัง

  const body = shown.map(f => {
    const lam = Math.max(0, dot(f.n, LIGHT));
    const tone = 0.20 + 0.80 * Math.pow(lam, 0.75);
    /* ลูกเต๋าจริงลบมุมทุกด้าน ขอบจึงรับแสงคนละมุมกับหน้าตรงกลาง
       ผลคือทุกหน้ามีกรอบเข้มบาง ๆ ล้อมอยู่ หันตรงเป๊ะก็ยังเห็นความหนา */
    return `<polygon points="${f.d}" fill="${mix(tone * 0.62)}" stroke="rgba(52,40,20,.42)"
      stroke-width="1" stroke-linejoin="round"/>
      <polygon points="${f.inner}" fill="${mix(tone)}" stroke="none"/>`;
  }).join('');

  let text = '';
  if (face != null) {
    const front = shown.reduce((best, f) => (!best || f.n[2] > best.n[2] ? f : best), null);
    if (front) {
      const size = Math.max(15, front.span * 1.15);
      text = `<text x="${front.mid[0].toFixed(2)}" y="${front.mid[1].toFixed(2)}"
        class="wr-die-num" font-size="${size.toFixed(1)}"
        text-anchor="middle" dominant-baseline="central">${face}</text>`;
    }
  }

  return `<svg viewBox="-50 -50 100 100" class="wr-die-art" aria-hidden="true">${body}${text}</svg>`;
}
